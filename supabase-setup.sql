-- Rulează acest fișier în SQL Editor-ul proiectului Supabase.
-- Creează utilizatorul administrator din Authentication > Users, apoi adaugă-i
-- UUID-ul în feedback_admins; același cont administrează review-urile și înscrierile.

create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  author_name text not null check (char_length(trim(author_name)) between 1 and 80),
  author_type text not null default 'spectator',
  message text not null check (char_length(trim(message)) between 1 and 2000),
  image_path text,
  created_at timestamptz not null default now()
);

alter table public.feedback
  add column if not exists author_type text not null default 'spectator';
alter table public.feedback
  add column if not exists author_name text;
alter table public.feedback
  add column if not exists image_path text;

do $$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'feedback'
      and column_name = 'name'
  ) then
    execute 'update public.feedback set author_name = coalesce(author_name, name::text)';
    execute 'alter table public.feedback alter column name drop not null';
  end if;

  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'feedback'
      and column_name = 'role'
  ) then
    execute 'alter table public.feedback alter column role drop not null';
  end if;
end;
$$;

alter table public.feedback
  drop constraint if exists feedback_author_type_check;
alter table public.feedback
  add constraint feedback_author_type_check
  check (author_type in ('participant', 'spectator', 'volunteer'));

alter table public.feedback enable row level security;
grant select, insert, delete on public.feedback to anon, authenticated;
do $$
declare
  feedback_id_sequence text;
begin
  feedback_id_sequence := pg_get_serial_sequence('public.feedback', 'id');
  if feedback_id_sequence is not null then
    execute format(
      'grant usage, select on sequence %s to anon, authenticated',
      feedback_id_sequence
    );
  end if;
end;
$$;

drop policy if exists "Anyone can read feedback" on public.feedback;
create policy "Anyone can read feedback"
  on public.feedback for select
  to anon, authenticated
  using (true);

drop policy if exists "Anyone can post feedback" on public.feedback;
create policy "Anyone can post feedback"
  on public.feedback for insert
  to anon, authenticated
  with check (true);

create table if not exists public.feedback_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

alter table public.feedback_admins enable row level security;
revoke all on public.feedback_admins from anon, authenticated;

create or replace function public.is_feedback_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.feedback_admins
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_feedback_admin() from public;
grant execute on function public.is_feedback_admin() to anon, authenticated;

drop policy if exists "Only feedback admins can delete feedback" on public.feedback;
create policy "Only feedback admins can delete feedback"
  on public.feedback for delete
  to authenticated
  using (public.is_feedback_admin());

